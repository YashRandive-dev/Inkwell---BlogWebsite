require('dotenv').config();

const mongoose = require('mongoose');
const connectDB = require('../config/db');
const User = require('../models/User');
const Category = require('../models/Category');
const Post = require('../models/Post');
const Comment = require('../models/Comment');

// Local-testing credentials only. Change or remove them before going live.
const ADMIN = { name: 'Inkwell Admin', email: 'admin@inkwell.com', password: 'Admin1234', role: 'admin', isVerified: true, bio: 'Editor of Inkwell. I love clean prose and good coffee.' };
const WRITER = { name: 'Jane Writer', email: 'jane@inkwell.com', password: 'Writer1234', isVerified: true, bio: 'Developer and part-time storyteller.' };

const categories = [
  { name: 'Technology', description: 'Software, gadgets and the web.' },
  { name: 'Lifestyle', description: 'Habits, travel and everyday life.' },
  { name: 'Productivity', description: 'Get more done with less stress.' },
  { name: 'Design', description: 'Visual thinking and user experience.' },
];

const img = (id) => ({ url: `https://images.unsplash.com/${id}?auto=format&fit=crop&w=1200&q=70`, public_id: '' });

const lorem = (title) => `
<p>${title} is a topic worth slowing down for. In this post we walk through the ideas, the trade-offs and a few practical steps you can try today.</p>
<h2>Why it matters</h2>
<p>Small, consistent improvements compound. Whether you are just starting out or have years of experience, revisiting the fundamentals pays off more than chasing every new trend.</p>
<blockquote>Good work is rarely loud. It is patient, deliberate and a little bit stubborn.</blockquote>
<h2>Getting started</h2>
<ul><li>Pick one small thing to change this week.</li><li>Write down what you expect to happen.</li><li>Review the result and adjust.</li></ul>
<p>Here is a tiny example you can adapt:</p>
<pre class="ql-syntax" spellcheck="false">const improve = (x) => x + 1;\nconsole.log(improve(1));</pre>
<h2>Wrapping up</h2>
<p>Thanks for reading. If this was useful, leave a comment and tell us what you would like to see next.</p>`;

const posts = [
  { title: 'Getting Started with the MERN Stack', category: 'Technology', tags: ['mern', 'javascript', 'beginners'], cover: 'photo-1555066931-4365d14bab8c', featured: true, excerpt: 'A friendly tour of MongoDB, Express, React and Node, and how they fit together.' },
  { title: 'Ten Habits of Highly Focused People', category: 'Productivity', tags: ['focus', 'habits'], cover: 'photo-1484480974693-6ca0a78fb36b', featured: true, excerpt: 'Simple routines that protect your attention in a noisy world.' },
  { title: 'Designing for Dark Mode Without the Headaches', category: 'Design', tags: ['ui', 'css', 'dark-mode'], cover: 'photo-1561070791-2526d30994b5', featured: true, excerpt: 'Colour tokens, contrast and a few gotchas when supporting both themes.' },
  { title: 'A Slow Morning Routine That Actually Sticks', category: 'Lifestyle', tags: ['routine', 'wellbeing'], cover: 'photo-1495474472287-4d71bcdd2085', featured: false, excerpt: 'No five a.m. alarm required. Just a calmer start to the day.' },
  { title: 'Understanding async/await Once and For All', category: 'Technology', tags: ['javascript', 'async'], cover: 'photo-1515879218367-8466d910aaa4', featured: false, excerpt: 'Promises, microtasks and why your function returns a Promise.' },
  { title: 'The Case for Writing in Public', category: 'Productivity', tags: ['writing', 'career'], cover: 'photo-1455390582262-044cdead277a', featured: false, excerpt: 'How sharing your notes builds skill, confidence and a network.' },
  { title: 'Typography Basics Every Developer Should Know', category: 'Design', tags: ['typography', 'ui'], cover: 'photo-1519682337058-a94d519337bc', featured: false, excerpt: 'Line length, line height and scale: the three levers that matter most.' },
  { title: 'Weekend Travel on a Budget', category: 'Lifestyle', tags: ['travel', 'budget'], cover: 'photo-1488646953014-85cb44e25828', featured: false, excerpt: 'Short trips, big memories, small spend.' },
];

const run = async () => {
  await connectDB();

  // Wipe existing data so the seed can be re-run safely.
  await Promise.all([User.deleteMany(), Category.deleteMany(), Post.deleteMany(), Comment.deleteMany()]);

  const admin = await User.create(ADMIN);
  const writer = await User.create(WRITER);
  const cats = await Category.create(categories);
  const catByName = Object.fromEntries(cats.map((c) => [c.name, c]));

  const created = [];
  for (let i = 0; i < posts.length; i += 1) {
    const p = posts[i];
    // Using create() one by one so slugs and reading times are generated by the model hooks.
    const post = await Post.create({
      title: p.title,
      excerpt: p.excerpt,
      content: lorem(p.title),
      category: catByName[p.category]._id,
      tags: p.tags,
      author: i % 2 === 0 ? admin._id : writer._id,
      status: 'published',
      featured: p.featured,
      coverImage: img(p.cover),
      views: Math.floor(Math.random() * 900) + 50,
      likes: [writer._id],
      likesCount: 1,
    });
    created.push(post);
  }

  // A draft and a couple of comments for the demo.
  await Post.create({
    title: 'Unfinished Thoughts on Minimalism',
    content: '<p>This one is still a draft.</p>',
    category: catByName.Lifestyle._id,
    tags: ['minimalism'],
    author: writer._id,
    status: 'draft',
  });
  const first = await Comment.create({ post: created[0]._id, user: writer._id, content: 'Great overview, very beginner friendly!' });
  await Comment.create({ post: created[0]._id, user: admin._id, content: 'Thanks Jane! More MERN guides coming soon.', parentComment: first._id });

  console.log('\nSeed complete.');
  console.log(`Admin login : ${ADMIN.email} / ${ADMIN.password}`);
  console.log(`User login  : ${WRITER.email} / ${WRITER.password}\n`);
  await mongoose.disconnect();
};

run().catch(async (error) => {
  console.error(`Seed failed: ${error.message}`);
  await mongoose.disconnect();
  process.exit(1);
});
